export type UserMessageKey = keyof typeof englishMessages;

/** Fills {placeholder} slots; an unmatched slot is left visible on purpose. */
export function translateMessage(
  key: UserMessageKey,
  values: Record<string, string | number> = {},
): string {
  return englishMessages[key].replace(
    /\{(\w+)\}/g,
    (_match, name: string) => String(values[name] ?? `{${name}}`),
  );
}
